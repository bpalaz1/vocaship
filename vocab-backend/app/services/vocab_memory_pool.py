# Ters indeks: (lang, normalized_token) -> english headword key
_REVERSE_VOCAB_INDEX: Dict[Tuple[str, str], str] = {}
for _en_word, _entry in MULTI_LANG_VOCAB.items():
    for _lang_code, _trans_str in (_entry.get("translations") or {}).items():
        for _variant in _trans_str.split(","):
            _norm = " ".join(_variant.strip().lower().split())
            if _norm and (_lang_code, _norm) not in _REVERSE_VOCAB_INDEX:
                _REVERSE_VOCAB_INDEX[(_lang_code, _norm)] = _en_word


def lookup_vocab_pool(
    word: str, target_lang: str, native_lang: str
) -> Optional[Dict[str, Any]]:
    """
    Yerel çok dilli havuzda (target_lang, native_lang, word) için KESİN eşleşme arar.
    İstenen native_lang bulunamazsa ASLA başka bir dile (örneğin Türkçe'ye) geri düşmez.
    """
    norm_word = " ".join((word or "").strip().lower().split())
    t_lang = (target_lang or "en").strip().lower()
    n_lang = (native_lang or "tr").strip().lower()
    if not norm_word:
        return None

    # 1. İngilizce kaynak kelime doğrudan eşleşmesi
    if t_lang == "en" and norm_word in MULTI_LANG_VOCAB:
        entry = MULTI_LANG_VOCAB[norm_word]
        example_target = entry.get("example_en", "")
        if n_lang == "en":
            en_def = entry.get("definition_en", "")
            if not en_def:
                return None
            return {
                "word": norm_word,
                "phonetic": entry.get("phonetic", f"/{norm_word}/"),
                "translation": en_def,
                "definition": en_def,
                "example_target": example_target,
                "example_native": "",
                "source": "common_vocab",
            }
        trans = (entry.get("translations") or {}).get(n_lang)
        if not trans:
            return None
        example_native = (entry.get("example_translations") or {}).get(n_lang, "")
        return {
            "word": norm_word,
            "phonetic": entry.get("phonetic", f"/{norm_word}/"),
            "translation": trans,
            "definition": entry.get("definition_en", ""),
            "example_target": example_target,
            "example_native": example_native if example_target else "",
            "source": "common_vocab",
        }

    # 2. İngilizce dışındaki kaynak diller için ters/çapraz dil eşleşmesi (ör. tr->ru, de->en, ru->tr)
    en_key = _REVERSE_VOCAB_INDEX.get((t_lang, norm_word))
    if en_key and en_key in MULTI_LANG_VOCAB:
        entry = MULTI_LANG_VOCAB[en_key]
        example_target = (entry.get("example_translations") or {}).get(t_lang, "")
        if n_lang == "en":
            translation = en_key
            example_native = entry.get("example_en", "") if example_target else ""
            definition = entry.get("definition_en", "")
        elif n_lang == t_lang:
            return None
        else:
            translation = (entry.get("translations") or {}).get(n_lang)
            if not translation:
                return None
            example_native = (
                (entry.get("example_translations") or {}).get(n_lang, "")
                if example_target
                else ""
            )
            definition = ""

        return {
            "word": norm_word,
            "phonetic": "",
            "translation": translation,
            "definition": definition,
            "example_target": example_target,
            "example_native": example_native,
            "source": "common_vocab",
        }

    return None
