export function pickLang<T>(map: Partial<Record<Language, T>>, lang?: Language | string): T;
export function pickLang<T>(lang: Language | string, map: Partial<Record<Language, T>>): T;
export function pickLang<T>(
  a: Partial<Record<Language, T>> | Language | string,
  b?: Language | string | Partial<Record<Language, T>>
): T {
  const map = (typeof a === "object" && a !== null ? a : (b as Partial<Record<Language, T>>)) || {};
  const rawLang = typeof a === "string" ? a : (b as string | undefined);
  const code = (rawLang || "tr").toLowerCase() as Language;
  return (map[code] ?? map.en ?? map.tr) as T;
}

