export type TranslationKey = keyof typeof UI_TRANSLATIONS.tr | keyof typeof KEY_ALIASES | (string & {});

export interface LanguageContextType {
  language: Language;
  currentLang: Language;
  setLanguage: (lang: Language) => void;
  t: (key: TranslationKey, fallback?: string, params?: Record<string, string | number>) => string;
  availableLanguages: LanguageOption[];
}

export const LanguageContext = createContext<LanguageContextType>({
  language: "tr",
  currentLang: "tr",
  setLanguage: () => {},
  t: (key: TranslationKey, fallback?: string) => fallback || String(key),
  availableLanguages: AVAILABLE_LANGUAGES,
});

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguageState] = useState<Language>("tr");

  useEffect(() => {
    try {
      const saved = (localStorage.getItem("vocaship_ui_lang") || localStorage.getItem("quizwise_ui_lang")) as Language | null;
      if (saved && (saved === "tr" || saved === "en" || saved === "de" || saved === "es" || saved === "fr")) {
        setLanguageState(saved);
      }
    } catch (e) {
      // localStorage erişilemezse varsayılan 'tr' kalır
    }
  }, []);

  const setLanguage = useCallback((lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem("quizwise_ui_lang", lang);
      localStorage.setItem("vocaship_ui_lang", lang);
    } catch (e) {
      // sessizce geç
    }
  }, []);

  const t = useCallback((key: TranslationKey, fallback?: string, params?: Record<string, string | number>): string => {
    const keyStr = String(key);
    const resolvedKey = KEY_ALIASES[keyStr] || keyStr;
    const currentDict = UI_TRANSLATIONS[language];
    const enDict = UI_TRANSLATIONS["en"];
    const trDict = UI_TRANSLATIONS["tr"];

    let result = "";

    // 1. Direct key in current language
    if (currentDict && currentDict[keyStr] !== undefined && currentDict[keyStr] !== "") {
      result = currentDict[keyStr];
    }
    // 2. Resolved alias in current language
    else if (currentDict && currentDict[resolvedKey] !== undefined && currentDict[resolvedKey] !== "") {
      result = currentDict[resolvedKey];
    }
    // 3. Fallback to English dictionary (if current language is not English)
    else if (language !== "en" && enDict && enDict[keyStr] !== undefined && enDict[keyStr] !== "") {
      result = enDict[keyStr];
    }
    else if (language !== "en" && enDict && enDict[resolvedKey] !== undefined && enDict[resolvedKey] !== "") {
      result = enDict[resolvedKey];
    }
    // 4. Fallback string if provided
    else if (fallback !== undefined && fallback !== "") {
      result = fallback;
    }
    // 5. Fallback to Turkish dictionary
    else if (trDict && trDict[keyStr] !== undefined && trDict[keyStr] !== "") {
      result = trDict[keyStr];
    }
    else if (trDict && trDict[resolvedKey] !== undefined && trDict[resolvedKey] !== "") {
      result = trDict[resolvedKey];
    }
    // 6. Return key string
    else {
      result = keyStr;
    }

    // Param replacement (e.g. {count}, {cur}, {total}, {xp}, {lang})
    if (params) {
      Object.entries(params).forEach(([paramKey, val]) => {
        result = result.replace(new RegExp(`\{${paramKey}\}`, "g"), String(val));
      });
    }

    return result;
  }, [language]);

  const value = useMemo<LanguageContextType>(() => ({
    language,
    currentLang: language,
    setLanguage,
    t,
    availableLanguages: AVAILABLE_LANGUAGES,
  }), [language, setLanguage, t]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
export const useTranslation = () => useContext(LanguageContext);
